//! 封包 / 拆包 —— 解决 TCP 粘包问题。
//!
//! TCP 是字节流,没有"消息边界"。我们自定义一个 TLV 协议:
//!
//!   +----------+----------+------------------+
//!   | dataLen  |  msgID   |      data ...     |
//!   |  u32(LE) |  u32(LE) |   dataLen 字节    |
//!   +----------+----------+------------------+
//!
//! 读的时候:先读固定 8 字节头 -> 得到 dataLen -> 再精确读 dataLen 字节 body。
//!
//! 阶段 1 目标:
//!   - pack(&Message) -> Vec<u8>          封包
//!   - unpack(head: &[u8]) -> (len, id)   只解头
//!   - HEAD_LEN 常量 = 8
